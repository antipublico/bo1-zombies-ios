#include <database/db_xmodel_header.h>
#include <platform/bo1_bytecode_io.h>
#include <array>
#include <cstdint>
#include <cstdio>
#include <cstring>

namespace
{
using Bytes = std::array<unsigned char, bo1::fastfile::XModelDiskHeaderSize + 1>;
unsigned checks = 0, failures = 0;
void Check(bool value, const char* label)
{
    ++checks;
    if (!value) { ++failures; std::fprintf(stderr, "FAIL: %s\n", label); }
}
template<class T> void Put(Bytes& data, std::size_t at, T value)
{
    bo1::bytecode::Store<T>(data.data() + 1 + at, value);
}
}

int main()
{
    using namespace bo1::fastfile;
    Bytes disk{};
    // Intentionally begin at byte 1 to exercise unaligned scalar loads.
    disk[1 + 4] = 8;
    disk[1 + 5] = 2;
    disk[1 + 6] = 12;
    disk[1 + 7] = 3;
    Put(disk, 0, 0xFFFFFFFFu);
    Put(disk, 8, 0x80000031u);
    Put(disk, 12, 0xFFFFFFFFu);
    Put(disk, 16, 0x80000020u);
    Put(disk, 20, 0x80000050u);
    Put(disk, 24, 0xFFFFFFFFu);
    Put(disk, 28, 0x80000060u);
    Put(disk, 32, 0xFFFFFFFFu);
    Put(disk, 36, 0xFFFFFFFEu);

    Put(disk, 40, 125.5f);
    Put(disk, 44, std::uint16_t(12));
    Put(disk, 46, std::uint16_t(0));
    Put(disk, 48, std::int32_t(0x12345678));
    disk[1 + 68] = 1;
    disk[1 + 69] = 2;
    disk[1 + 70] = 3;
    Put(disk, 72, 180.25f);
    Put(disk, 76, std::uint16_t(6));
    Put(disk, 78, std::uint16_t(6));
    disk[1 + 168] = 1;
    Put(disk, 172, 0xFFFFFFFFu);
    Put(disk, 176, std::int32_t(3));
    Put(disk, 180, std::int32_t(-123));
    Put(disk, 184, 0xFFFFFFFFu);
    Put(disk, 188, 42.25f);
    Put(disk, 192, -5.0f);
    Put(disk, 196, -6.0f);
    Put(disk, 200, -7.0f);
    Put(disk, 204, 5.0f);
    Put(disk, 208, 6.0f);
    Put(disk, 212, 7.0f);
    Put(disk, 216, std::int16_t(2));
    Put(disk, 218, std::int16_t(-1));
    Put(disk, 220, 0x800000A1u);
    Put(disk, 224, std::int32_t(4096));
    Put(disk, 228, std::int32_t(17));
    disk[1 + 232] = 1;
    Put(disk, 236, 0xFFFFFFFFu);
    disk[1 + 240] = 2;
    Put(disk, 244, 0x80000011u);
    Put(disk, 248, 0xFFFFFFFEu);

    XModelHeader decoded;
    Check(DecodeXModelHeader(disk.data() + 1, XModelDiskHeaderSize, decoded),
        "decode complete unaligned XModel header");
    Check(decoded.nameTag == 0xFFFFFFFFu, "name Win32 tag retained");
    Check(decoded.numBones == 8 && decoded.numRootBones == 2
        && decoded.numSurfaces == 12 && decoded.lodRampType == 3, "bone and surface counts");
    Check(decoded.boneNamesTag == 0x80000031u && decoded.parentListTag == UINT32_MAX
        && decoded.quaternionsTag == 0x80000020u && decoded.translationsTag == 0x80000050u,
        "bone tags retain serialized values");
    Check(decoded.classificationsTag == UINT32_MAX
        && decoded.baseMatricesTag == 0x80000060u
        && decoded.surfacesTag == UINT32_MAX
        && decoded.materialsTag == UINT32_MAX - 1,
        "geometry and material tags retain serialized values");
    Check(decoded.lods[0].distance == 125.5f && decoded.lods[0].surfaceCount == 12
        && decoded.lods[0].firstSurface == 0 && decoded.lods[0].partBits[0] == 0x12345678
        && decoded.lods[0].lod == 1 && decoded.lods[0].smcIndexPlusOne == 2
        && decoded.lods[0].smcAllocBits == 3, "LOD0 offsets and attributes");
    Check(decoded.lods[1].distance == 180.25f && decoded.lods[1].surfaceCount == 6
        && decoded.lods[1].firstSurface == 6, "LOD1 offsets");
    Check(decoded.lodDistancesAutoGenerated == 1 && decoded.numLods == 2
        && decoded.collisionLod == -1, "LOD fields");
    Check(decoded.collisionSurfacesTag == UINT32_MAX && decoded.numCollisionSurfaces == 3
        && decoded.contents == -123 && decoded.boneInfoTag == UINT32_MAX,
        "collision metadata");
    Check(decoded.radius == 42.25f && decoded.mins[0] == -5.f
        && decoded.mins[1] == -6.f && decoded.mins[2] == -7.f
        && decoded.maxs[0] == 5.f && decoded.maxs[1] == 6.f
        && decoded.maxs[2] == 7.f, "bounds and radius");
    Check(decoded.highMipBoundsTag == 0x800000A1u && decoded.memoryUsage == 4096
        && decoded.flags == 17 && decoded.bad == 1, "stream and runtime flags");
    Check(decoded.physicsPresetTag == UINT32_MAX && decoded.numCollisionMaps == 2
        && decoded.collisionMapsTag == 0x80000011u
        && decoded.physicsConstraintsTag == UINT32_MAX - 1,
        "physics and collmap pointers");
    const auto inlineBytes = CalculateXModelInlineBytes(decoded);
    Check(inlineBytes.boneNames == 0 && inlineBytes.parentList == 6
        && inlineBytes.quaternions == 0 && inlineBytes.translations == 0
        && inlineBytes.classifications == 8 && inlineBytes.baseMatrices == 0,
        "bone arrays count only explicit inline Win32 tags");
    Check(inlineBytes.surfaceHeaders == 816 && inlineBytes.materialPointerArray == 48
        && inlineBytes.collisionSurfaceHeaders == 132 && inlineBytes.boneInfo == 352
        && inlineBytes.highMipBounds == 192 && inlineBytes.collisionMapHeaders == 8,
        "fixed-size surface, collision and geometry array budgets");
    Check(inlineBytes.Total() == 1562, "model fixed-size inline byte total");
    auto extraInline = disk;
    Put(extraInline, 8, UINT32_MAX);
    Put(extraInline, 16, UINT32_MAX);
    Put(extraInline, 20, UINT32_MAX);
    Put(extraInline, 28, UINT32_MAX);
    Put(extraInline, 32, 0u);
    Put(extraInline, 36, 0u);
    Put(extraInline, 172, 0u);
    Put(extraInline, 184, 0u);
    Put(extraInline, 220, 0u);
    Put(extraInline, 244, 0u);
    XModelHeader alternative;
    Check(DecodeXModelHeader(extraInline.data() + 1, XModelDiskHeaderSize, alternative),
        "decode skeletal-only inline model variant");
    const auto alternativeBytes = CalculateXModelInlineBytes(alternative);
    Check(alternativeBytes.boneNames == 16 && alternativeBytes.quaternions == 48
        && alternativeBytes.translations == 96 && alternativeBytes.baseMatrices == 256,
        "model skeletal payload respects native Win32 child byte counts");
    Check(alternativeBytes.surfaceHeaders == 0 && alternativeBytes.materialPointerArray == 0
        && alternativeBytes.collisionSurfaceHeaders == 0 && alternativeBytes.boneInfo == 0
        && alternativeBytes.highMipBounds == 0 && alternativeBytes.collisionMapHeaders == 0,
        "absent child arrays allocate no bytes");
    Check(!DecodeXModelHeader(disk.data() + 1, XModelDiskHeaderSize - 1, decoded)
        && decoded.nameTag == 0, "reject truncated buffer without publishing state");
    Check(!DecodeXModelHeader(nullptr, XModelDiskHeaderSize, decoded)
        && decoded.numSurfaces == 0, "reject null input");

    const auto fixture = disk;
    Put(disk, 216, std::int16_t(5));
    Check(!DecodeXModelHeader(disk.data() + 1, XModelDiskHeaderSize, decoded),
        "reject unsupported number of LODs");
    disk = fixture;
    Put(disk, 216, std::int16_t(-1));
    Check(!DecodeXModelHeader(disk.data() + 1, XModelDiskHeaderSize, decoded),
        "reject negative LOD count");
    disk = fixture;
    disk[1 + 5] = 9;
    Check(!DecodeXModelHeader(disk.data() + 1, XModelDiskHeaderSize, decoded),
        "reject root bone count larger than all bones");
    disk = fixture;
    Put(disk, 176, std::int32_t(-1));
    Check(!DecodeXModelHeader(disk.data() + 1, XModelDiskHeaderSize, decoded),
        "reject negative collision surface count");
    disk = fixture;
    Put(disk, 78, std::uint16_t(7));
    Check(!DecodeXModelHeader(disk.data() + 1, XModelDiskHeaderSize, decoded),
        "reject LOD exceeding surface count");
    disk = fixture;
    Put(disk, 76, std::uint16_t(13));
    Check(!DecodeXModelHeader(disk.data() + 1, XModelDiskHeaderSize, decoded),
        "reject LOD surface count larger than all surfaces");
    disk = fixture;
    Put(disk, 76, std::uint16_t(0));
    Put(disk, 78, std::uint16_t(12));
    Check(DecodeXModelHeader(disk.data() + 1, XModelDiskHeaderSize, decoded),
        "allow empty LOD at last surface boundary");
    disk = fixture;
    Put(disk, 108, std::uint16_t(65535)); // Unused LOD2 must not be validated.
    Check(DecodeXModelHeader(disk.data() + 1, XModelDiskHeaderSize, decoded),
        "ignore inactive LOD metadata");

    std::printf("%u XModel header checks, %u failures\n", checks, failures);
    return failures != 0;
}
