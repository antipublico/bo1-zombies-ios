#pragma once

#include <platform/bo1_bytecode_io.h>
#include <cstddef>
#include <cstdint>

// The 252-byte serialized XModel header is the Win32 layout in
// xanim/xmodel.h and database/db_load.cpp::Load_XModel. These are intentionally
// value-only metadata types: serialized tags must not become native pointers.
namespace bo1::fastfile
{
constexpr std::size_t XModelDiskHeaderSize = 252;

struct XModelLodHeader
{
    float distance = 0;
    std::uint16_t surfaceCount = 0;
    std::uint16_t firstSurface = 0;
    std::int32_t partBits[5]{};
    std::uint8_t lod = 0;
    std::uint8_t smcIndexPlusOne = 0;
    std::uint8_t smcAllocBits = 0;
};

struct XModelHeader
{
    std::uint32_t nameTag = 0;
    std::uint8_t numBones = 0;
    std::uint8_t numRootBones = 0;
    std::uint8_t numSurfaces = 0;
    std::uint8_t lodRampType = 0;

    std::uint32_t boneNamesTag = 0;
    std::uint32_t parentListTag = 0;
    std::uint32_t quaternionsTag = 0;
    std::uint32_t translationsTag = 0;
    std::uint32_t classificationsTag = 0;
    std::uint32_t baseMatricesTag = 0;
    std::uint32_t surfacesTag = 0;
    std::uint32_t materialsTag = 0;

    XModelLodHeader lods[4]{};
    std::uint8_t lodDistancesAutoGenerated = 0;
    std::uint32_t collisionSurfacesTag = 0;
    std::int32_t numCollisionSurfaces = 0;
    std::int32_t contents = 0;
    std::uint32_t boneInfoTag = 0;
    float radius = 0;
    float mins[3]{};
    float maxs[3]{};
    std::int16_t numLods = 0;
    std::int16_t collisionLod = 0;
    std::uint32_t highMipBoundsTag = 0;
    std::int32_t memoryUsage = 0;
    std::int32_t flags = 0;
    std::uint8_t bad = 0;
    std::uint32_t physicsPresetTag = 0;
    std::uint8_t numCollisionMaps = 0;
    std::uint32_t collisionMapsTag = 0;
    std::uint32_t physicsConstraintsTag = 0;
};

// The fixed-size inline arrays in db_load.cpp::Load_XModel, excluding strings,
// nested surface payloads, materials, collision trees and physics subobjects.
// These sizes are useful for preflight limits, not enough to reconstruct models.
struct XModelInlineBytes
{
    std::uint64_t boneNames = 0;
    std::uint64_t parentList = 0;
    std::uint64_t quaternions = 0;
    std::uint64_t translations = 0;
    std::uint64_t classifications = 0;
    std::uint64_t baseMatrices = 0;
    std::uint64_t surfaceHeaders = 0;
    std::uint64_t materialPointerArray = 0;
    std::uint64_t collisionSurfaceHeaders = 0;
    std::uint64_t boneInfo = 0;
    std::uint64_t highMipBounds = 0;
    std::uint64_t collisionMapHeaders = 0;

    std::uint64_t Total() const noexcept
    {
        return boneNames + parentList + quaternions + translations
            + classifications + baseMatrices + surfaceHeaders
            + materialPointerArray + collisionSurfaceHeaders + boneInfo
            + highMipBounds + collisionMapHeaders;
    }
};

// These counts are uint8/validated nonnegative int32, and all products fit
// uint64_t. Load_XModel tests some fields for -1 and others for any nonzero:
// preserve that distinction when budgeting.
inline XModelInlineBytes CalculateXModelInlineBytes(const XModelHeader& model) noexcept
{
    XModelInlineBytes bytes{};
    const auto otherBones = std::uint64_t(model.numBones - model.numRootBones);
    if (model.boneNamesTag == UINT32_MAX) bytes.boneNames = std::uint64_t(model.numBones) * 2;
    if (model.parentListTag == UINT32_MAX) bytes.parentList = otherBones;
    if (model.quaternionsTag == UINT32_MAX) bytes.quaternions = otherBones * 8;
    if (model.translationsTag == UINT32_MAX) bytes.translations = otherBones * 16;
    if (model.classificationsTag == UINT32_MAX) bytes.classifications = model.numBones;
    if (model.baseMatricesTag == UINT32_MAX) bytes.baseMatrices = std::uint64_t(model.numBones) * 32;
    if (model.surfacesTag) bytes.surfaceHeaders = std::uint64_t(model.numSurfaces) * 68;
    if (model.materialsTag) bytes.materialPointerArray = std::uint64_t(model.numSurfaces) * 4;
    if (model.collisionSurfacesTag && model.numCollisionSurfaces >= 0)
        bytes.collisionSurfaceHeaders = std::uint64_t(model.numCollisionSurfaces) * 44;
    if (model.boneInfoTag) bytes.boneInfo = std::uint64_t(model.numBones) * 44;
    if (model.highMipBoundsTag) bytes.highMipBounds = std::uint64_t(model.numSurfaces) * 16;
    if (model.collisionMapsTag) bytes.collisionMapHeaders = std::uint64_t(model.numCollisionMaps) * 4;
    return bytes;
}

// Read exact Win32 byte offsets, not sizeof(XModel) on the current platform.
// This only validates the independent header; child pointers, stream bounds,
// materials and collision bodies must be checked by the later native loader.
inline bool DecodeXModelHeader(const unsigned char* bytes, std::size_t size,
    XModelHeader& output) noexcept
{
    output = {};
    if (!bytes || size < XModelDiskHeaderSize) return false;

    XModelHeader result;
    auto u32 = [&](std::size_t i) { return bytecode::Load<std::uint32_t>(bytes + i); };
    auto i32 = [&](std::size_t i) { return bytecode::Load<std::int32_t>(bytes + i); };
    auto i16 = [&](std::size_t i) { return bytecode::Load<std::int16_t>(bytes + i); };
    auto f32 = [&](std::size_t i) { return bytecode::Load<float>(bytes + i); };

    result.nameTag = u32(0);
    result.numBones = bytes[4];
    result.numRootBones = bytes[5];
    result.numSurfaces = bytes[6];
    result.lodRampType = bytes[7];

    result.boneNamesTag = u32(8);
    result.parentListTag = u32(12);
    result.quaternionsTag = u32(16);
    result.translationsTag = u32(20);
    result.classificationsTag = u32(24);
    result.baseMatricesTag = u32(28);
    result.surfacesTag = u32(32);
    result.materialsTag = u32(36);

    for (std::size_t i = 0; i < 4; ++i)
    {
        const auto base = 40 + 32 * i;
        auto& lod = result.lods[i];
        lod.distance = f32(base);
        lod.surfaceCount = bytecode::Load<std::uint16_t>(bytes + base + 4);
        lod.firstSurface = bytecode::Load<std::uint16_t>(bytes + base + 6);
        for (std::size_t j = 0; j < 5; ++j)
            lod.partBits[j] = i32(base + 8 + 4 * j);
        lod.lod = bytes[base + 28];
        lod.smcIndexPlusOne = bytes[base + 29];
        lod.smcAllocBits = bytes[base + 30];
    }

    result.lodDistancesAutoGenerated = bytes[168];
    result.collisionSurfacesTag = u32(172);
    result.numCollisionSurfaces = i32(176);
    result.contents = i32(180);
    result.boneInfoTag = u32(184);
    result.radius = f32(188);
    for (std::size_t i = 0; i < 3; ++i)
    {
        result.mins[i] = f32(192 + 4 * i);
        result.maxs[i] = f32(204 + 4 * i);
    }
    result.numLods = i16(216);
    result.collisionLod = i16(218);
    result.highMipBoundsTag = u32(220);
    result.memoryUsage = i32(224);
    result.flags = i32(228);
    result.bad = bytes[232];
    result.physicsPresetTag = u32(236);
    result.numCollisionMaps = bytes[240];
    result.collisionMapsTag = u32(244);
    result.physicsConstraintsTag = u32(248);

    if (result.numRootBones > result.numBones || result.numLods < 0
        || result.numLods > 4 || result.numCollisionSurfaces < 0) return false;

    for (int i = 0; i < result.numLods; ++i)
    {
        const auto& lod = result.lods[i];
        if (lod.firstSurface > result.numSurfaces
            || lod.surfaceCount > result.numSurfaces - lod.firstSurface)
            return false;
    }

    output = result;
    return true;
}
}
